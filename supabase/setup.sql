create extension if not exists "pgcrypto";

-- ---------- TABLES ----------
create table if not exists public.rooms (
  id            uuid primary key default gen_random_uuid(),
  code          text unique not null,
  host_id       uuid not null,
  phase         text not null default 'lobby'
                check (phase in ('lobby','prompts','guessing','voting','reveal')),
  round_index   int  not null default 0,
  created_at    timestamptz not null default now(),
  started_at    timestamptz,
  ended_at      timestamptz
);
create index if not exists rooms_code_idx on public.rooms (code);

create table if not exists public.players (
  id            uuid primary key default gen_random_uuid(),
  room_id       uuid not null references public.rooms(id) on delete cascade,
  auth_uid      uuid not null,
  display_name  text not null check (char_length(display_name) between 1 and 20),
  emoji         text not null default '😎',
  score         int  not null default 0,
  joined_at     timestamptz not null default now(),
  unique (room_id, auth_uid),
  unique (room_id, display_name)
);
create index if not exists players_room_idx on public.players (room_id);

create table if not exists public.prompt_catalog (
  id       int primary key generated by default as identity,
  kind     text not null check (kind in ('answer','vote')),
  text     text not null,
  active   boolean not null default true
);

create table if not exists public.answers (
  id           uuid primary key default gen_random_uuid(),
  room_id      uuid not null references public.rooms(id) on delete cascade,
  round_index  int  not null,
  author_id    uuid not null references public.players(id) on delete cascade,
  prompt_id    int  not null references public.prompt_catalog(id),
  body         text not null check (char_length(body) between 1 and 280),
  created_at   timestamptz not null default now(),
  unique (room_id, round_index, author_id, prompt_id)
);
create index if not exists answers_room_idx on public.answers (room_id, round_index);

create table if not exists public.guesses (
  id           uuid primary key default gen_random_uuid(),
  room_id      uuid not null references public.rooms(id) on delete cascade,
  round_index  int  not null,
  answer_id    uuid not null references public.answers(id) on delete cascade,
  guesser_id   uuid not null references public.players(id) on delete cascade,
  guessed_id   uuid not null references public.players(id) on delete cascade,
  correct      boolean not null default false,
  created_at   timestamptz not null default now(),
  unique (answer_id, guesser_id)
);
create index if not exists guesses_room_idx on public.guesses (room_id, round_index);

create table if not exists public.votes (
  id           uuid primary key default gen_random_uuid(),
  room_id      uuid not null references public.rooms(id) on delete cascade,
  round_index  int  not null,
  prompt_id    int  not null references public.prompt_catalog(id),
  voter_id     uuid not null references public.players(id) on delete cascade,
  target_id    uuid not null references public.players(id) on delete cascade,
  created_at   timestamptz not null default now(),
  unique (room_id, round_index, prompt_id, voter_id)
);
create index if not exists votes_room_idx on public.votes (room_id, round_index);

create table if not exists public.awards (
  id           uuid primary key default gen_random_uuid(),
  room_id      uuid not null references public.rooms(id) on delete cascade,
  title        text not null,
  player_id    uuid references public.players(id) on delete cascade,
  detail       text,
  created_at   timestamptz not null default now()
);
create index if not exists awards_room_idx on public.awards (room_id);

