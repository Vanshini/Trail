-- ---------- GAME FUNCTIONS ----------
create or replace function public._me(p_room uuid)
returns public.players
language sql stable security definer set search_path = public as $$
  select * from public.players
  where room_id = p_room and auth_uid = auth.uid()
  limit 1;
$$;

create or replace function public.create_room(p_name text, p_emoji text)
returns public.rooms
language plpgsql security definer set search_path = public as $$
declare v_code text; v_room public.rooms;
begin
  if length(trim(p_name)) < 1 then raise exception 'name required'; end if;
  loop
    v_code := upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
    exit when not exists (select 1 from public.rooms where code = v_code);
  end loop;
  insert into public.rooms (code, host_id) values (v_code, auth.uid())
    returning * into v_room;
  insert into public.players (room_id, auth_uid, display_name, emoji)
    values (v_room.id, auth.uid(), trim(p_name), p_emoji);
  return v_room;
end $$;

create or replace function public.join_room(p_code text, p_name text, p_emoji text)
returns public.rooms
language plpgsql security definer set search_path = public as $$
declare v_room public.rooms; v_count int;
begin
  select * into v_room from public.rooms where code = upper(trim(p_code));
  if v_room.id is null then raise exception 'room not found'; end if;
  if v_room.phase <> 'lobby' then raise exception 'game already started'; end if;
  select count(*) into v_count from public.players where room_id = v_room.id;
  if v_count >= 4 then raise exception 'room full'; end if;
  if exists (select 1 from public.players
             where room_id = v_room.id and auth_uid = auth.uid()) then
    return v_room;
  end if;
  insert into public.players (room_id, auth_uid, display_name, emoji)
    values (v_room.id, auth.uid(), trim(p_name), p_emoji);
  return v_room;
end $$;

create or replace function public.start_game(p_room uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_count int; v_host uuid;
begin
  select host_id into v_host from public.rooms where id = p_room for update;
  if v_host <> auth.uid() then raise exception 'only host can start'; end if;
  select count(*) into v_count from public.players where room_id = p_room;
  if v_count <> 4 then raise exception 'need exactly 4 players'; end if;
  update public.rooms
     set phase = 'prompts', started_at = now(), round_index = 0
   where id = p_room;
end $$;

create or replace function public.submit_answer(p_room uuid, p_prompt_id int, p_body text)
returns void language plpgsql security definer set search_path = public as $$
declare v_me public.players; v_room public.rooms;
begin
  select * into v_room from public.rooms where id = p_room;
  if v_room.phase <> 'prompts' then raise exception 'not in prompts phase'; end if;
  select * into v_me from public._me(p_room);
  if v_me.id is null then raise exception 'not in room'; end if;
  if length(trim(p_body)) < 1 then raise exception 'empty answer'; end if;
  insert into public.answers (room_id, round_index, author_id, prompt_id, body)
    values (p_room, v_room.round_index, v_me.id, p_prompt_id, trim(p_body))
    on conflict (room_id, round_index, author_id, prompt_id)
    do update set body = excluded.body;
end $$;

create or replace function public.advance_to_guessing(p_room uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_host uuid; v_round int; v_need int; v_have int;
begin
  select host_id, round_index into v_host, v_round from public.rooms
    where id = p_room for update;
  if v_host <> auth.uid() then raise exception 'only host'; end if;
  select count(*) * 2 into v_need from public.players where room_id = p_room;
  select count(*) into v_have from public.answers
   where room_id = p_room and round_index = v_round;
  if v_have < v_need then raise exception 'waiting for answers'; end if;
  update public.rooms set phase = 'guessing' where id = p_room;
end $$;

create or replace function public.submit_guess(p_room uuid, p_answer uuid, p_guessed uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_me public.players; v_room public.rooms; v_ans public.answers;
begin
  select * into v_room from public.rooms where id = p_room;
  if v_room.phase <> 'guessing' then raise exception 'not guessing'; end if;
  select * into v_me from public._me(p_room);
  select * into v_ans from public.answers where id = p_answer and room_id = p_room;
  if v_ans.id is null then raise exception 'bad answer'; end if;
  if v_ans.author_id = v_me.id then raise exception 'cannot guess own'; end if;
  insert into public.guesses (room_id, round_index, answer_id, guesser_id, guessed_id, correct)
    values (p_room, v_room.round_index, p_answer, v_me.id, p_guessed, p_guessed = v_ans.author_id)
    on conflict (answer_id, guesser_id)
    do update set guessed_id = excluded.guessed_id, correct = excluded.correct;
end $$;

create or replace function public.advance_to_voting(p_room uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_host uuid; v_round int; v_total int; v_done int; v_players int;
begin
  select host_id, round_index into v_host, v_round from public.rooms
    where id = p_room for update;
  if v_host <> auth.uid() then raise exception 'only host'; end if;
  select count(*) into v_players from public.players where room_id = p_room;
  select count(*) into v_total from public.answers
    where room_id = p_room and round_index = v_round;
  v_total := v_total * (v_players - 1);
  select count(*) into v_done from public.guesses
    where room_id = p_room and round_index = v_round;
  if v_done < v_total then raise exception 'waiting for guesses'; end if;

  update public.players p
     set score = p.score + coalesce((
       select count(*) from public.guesses g
        where g.guesser_id = p.id and g.room_id = p_room
          and g.round_index = v_round and g.correct
     ), 0) * 10
   where p.room_id = p_room;

  update public.rooms set phase = 'voting' where id = p_room;
end $$;

create or replace function public.submit_vote(p_room uuid, p_prompt_id int, p_target uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_me public.players; v_room public.rooms;
begin
  select * into v_room from public.rooms where id = p_room;
  if v_room.phase <> 'voting' then raise exception 'not voting'; end if;
  select * into v_me from public._me(p_room);
  if v_me.id = p_target then raise exception 'cannot vote self'; end if;
  insert into public.votes (room_id, round_index, prompt_id, voter_id, target_id)
    values (p_room, v_room.round_index, p_prompt_id, v_me.id, p_target)
    on conflict (room_id, round_index, prompt_id, voter_id)
    do update set target_id = excluded.target_id;
end $$;

create or replace function public.finalize_game(p_room uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_host uuid; v_round int; v_votes int; v_players int;
begin
  select host_id, round_index into v_host, v_round from public.rooms
    where id = p_room for update;
  if v_host <> auth.uid() then raise exception 'only host'; end if;

  select count(*) into v_players from public.players where room_id = p_room;
  select count(*) into v_votes from public.votes
    where room_id = p_room and round_index = v_round;
  if v_votes < v_players * 3 then raise exception 'waiting for votes'; end if;

  update public.players p
     set score = p.score + coalesce((
       select count(*) from public.votes v
        where v.target_id = p.id and v.room_id = p_room
          and v.round_index = v_round
     ), 0) * 5
   where p.room_id = p_room;

  delete from public.awards where room_id = p_room;

  insert into public.awards (room_id, title, player_id, detail)
  select p_room, 'Best Detective', p.id, (count(*) || ' correct guesses')::text
    from public.players p
    left join public.guesses g
      on g.guesser_id = p.id and g.room_id = p_room
         and g.round_index = v_round and g.correct
   where p.room_id = p_room
   group by p.id
   order by count(*) desc, p.joined_at asc
   limit 1;

  insert into public.awards (room_id, title, player_id, detail)
  select p_room, 'Most Loved', p.id, (count(v.id) || ' votes')::text
    from public.players p
    left join public.votes v
      on v.target_id = p.id and v.room_id = p_room and v.round_index = v_round
   where p.room_id = p_room
   group by p.id
   order by count(v.id) desc, p.joined_at asc
   limit 1;

  insert into public.awards (room_id, title, player_id, detail)
  select p_room, 'Wildest Imagination', a.author_id, (length(a.body) || ' chars')::text
    from public.answers a
   where a.room_id = p_room and a.round_index = v_round
   order by length(a.body) desc
   limit 1;

  insert into public.awards (room_id, title, player_id, detail)
  select p_room, 'The One Nobody Gets', a.author_id, (count(*) || ' misses')::text
    from public.answers a
    join public.guesses g on g.answer_id = a.id
   where a.room_id = p_room and a.round_index = v_round and g.correct = false
   group by a.author_id
   order by count(*) desc, random()
   limit 1;

  update public.rooms set phase = 'reveal', ended_at = now() where id = p_room;
end $$;

create or replace function public.restart_room(p_room uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_host uuid;
begin
  select host_id into v_host from public.rooms where id = p_room for update;
  if v_host <> auth.uid() then raise exception 'only host'; end if;
  delete from public.answers where room_id = p_room;
  delete from public.guesses where room_id = p_room;
  delete from public.votes   where room_id = p_room;
  delete from public.awards  where room_id = p_room;
  update public.players set score = 0 where room_id = p_room;
  update public.rooms
     set phase = 'lobby', round_index = round_index + 1,
         started_at = null, ended_at = null
   where id = p_room;
end $$;

